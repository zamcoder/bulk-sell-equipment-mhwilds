lang.EN = EN
local current = EN

function lang.T(key, ...)
    local text = current[key] or EN[key]
    if not text then return key end
    if select("#", ...) == 0 then return text end
    local ok, result = pcall(string.format, text, ...)
    return ok and result or text
end

return lang
